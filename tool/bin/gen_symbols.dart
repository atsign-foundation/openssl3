/// Generates `packages/openssl3/lib/src/symbols.dart` from OpenSSL's
/// `util/libcrypto.num` and a generated `configuration.h`.
///
///     dart run tool/bin/gen_symbols.dart --configuration-h <path>
///
/// The output records, for the feature set this package builds with, the
/// symbols exported on Unix-like targets and on Windows, and which of them are
/// deprecated (from the `DEPRECATEDIN_*` tags). Tests and the wasm export list
/// consume it; `--check` verifies the committed file is current.
library;

import 'dart:io';

import 'package:args/args.dart';
import 'package:openssl3/src/native_build/abi.dart';
import 'package:path/path.dart' as p;

Future<void> main(List<String> args) async {
  final parser = ArgParser()
    ..addOption('source', defaultsTo: 'third_party/openssl')
    ..addOption(
      'configuration-h',
      help: 'Generated include/openssl/configuration.h from a build',
    )
    ..addOption('output', defaultsTo: 'packages/openssl3/lib/src/symbols.dart')
    ..addFlag('check', negatable: false, help: 'Fail if output is stale');
  final opts = parser.parse(args);

  final source = Directory(opts.option('source')!);
  final configurationH = opts.option('configuration-h');
  if (configurationH == null) {
    stderr.writeln('--configuration-h is required (from any target build)');
    exit(64);
  }
  final disabled = disabledFeaturesFromConfigurationHeader(
    File(configurationH).readAsStringSync(),
  );
  final entries = AbiEntry.parseFile(
    File(p.join(source.path, 'util', 'libcrypto.num')),
  );
  final version = _readVersion(source);

  final unix = exportedEntries(
    entries,
    platform: AbiPlatform.unix,
    disabled: disabled,
  );
  final windows = exportedEntries(
    entries,
    platform: AbiPlatform.windows,
    disabled: disabled,
  );
  final unixNames = unix.map((e) => e.name).toSet();
  final windowsNames = windows.map((e) => e.name).toSet();
  final common = unixNames.intersection(windowsNames).toList()..sort();
  final unixOnly = unixNames.difference(windowsNames).toList()..sort();
  final windowsOnly = windowsNames.difference(unixNames).toList()..sort();
  final deprecated = <String, String>{
    for (final e in [...unix, ...windows]) e.name: ?e.deprecatedIn,
  };
  final deprecatedKeys = deprecated.keys.toList()..sort();
  final disabledSorted = disabled.toList()..sort();

  final b = StringBuffer()
    ..writeln(
      '// GENERATED by tool/bin/gen_symbols.dart from OpenSSL '
      '$version util/libcrypto.num.',
    )
    ..writeln('// Do not edit by hand.')
    ..writeln()
    ..writeln('// dart format off')
    ..writeln()
    ..writeln('/// OpenSSL version whose ABI list produced this file.')
    ..writeln("const String opensslAbiVersion = '$version';")
    ..writeln()
    ..writeln(
      '/// `Configure` features disabled in every shipped library '
      '(`OPENSSL_NO_*`).',
    )
    ..writeln('const Set<String> disabledFeatures = {')
    ..writeAll(disabledSorted.map((s) => "  '$s',\n"))
    ..writeln('};')
    ..writeln()
    ..writeln('/// Symbols exported on every target.')
    ..writeln('const Set<String> commonSymbols = {')
    ..writeAll(common.map((s) => "  '$s',\n"))
    ..writeln('};')
    ..writeln()
    ..writeln('/// Symbols exported only on Unix-like targets.')
    ..writeln('const Set<String> unixOnlySymbols = {')
    ..writeAll(unixOnly.map((s) => "  '$s',\n"))
    ..writeln('};')
    ..writeln()
    ..writeln('/// Symbols exported only on Windows.')
    ..writeln('const Set<String> windowsOnlySymbols = {')
    ..writeAll(windowsOnly.map((s) => "  '$s',\n"))
    ..writeln('};')
    ..writeln()
    ..writeln(
      '/// Deprecated symbols and the OpenSSL version that deprecated '
      'them.',
    )
    ..writeln('const Map<String, String> deprecatedSymbols = {')
    ..writeAll(deprecatedKeys.map((s) => "  '$s': '${deprecated[s]}',\n"))
    ..writeln('};');

  final output = File(opts.option('output')!);
  final content = b.toString();
  if (opts.flag('check')) {
    if (!output.existsSync() || output.readAsStringSync() != content) {
      stderr.writeln('${output.path} is stale; re-run gen_symbols.dart');
      exit(1);
    }
    stdout.writeln('${output.path} is up to date');
    return;
  }
  output.parent.createSync(recursive: true);
  output.writeAsStringSync(content);
  stdout.writeln(
    'Wrote ${output.path}: ${common.length} common, '
    '${unixOnly.length} unix-only, ${windowsOnly.length} windows-only, '
    '${deprecated.length} deprecated',
  );
}

String _readVersion(Directory source) {
  final lines = File(p.join(source.path, 'VERSION.dat')).readAsLinesSync();
  String get(String k) =>
      lines.firstWhere((l) => l.startsWith('$k=')).split('=')[1].trim();
  return '${get('MAJOR')}.${get('MINOR')}.${get('PATCH')}';
}
